#!/usr/bin/env bash
# Regenerate ~/.config/niri/dms/dictation-ptt.kdl from dictation-ptt config.json.
#
# Real press/release PTT is handled by dictation-ptt-keys (evdev). When
# keyboard_daemon is true (default), this file is emptied so niri does not
# double-fire on Scroll_Lock. When the daemon is disabled, toggle-only bind
# is written as a fallback (niri still has no Key+Release).
set -euo pipefail

CFG="${DICTATION_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/dictation-ptt/config.json}"
OUT="${NIRI_DMS_BINDS:-${XDG_CONFIG_HOME:-$HOME/.config}/niri/dms/dictation-ptt.kdl}"
BIN="${DICTATION_BIN:-/run/current-system/sw/bin/dictation-ptt}"

MODE=toggle
KEY=Pause
DAEMON=true

if [[ -f "$CFG" ]]; then
  if command -v jq >/dev/null 2>&1; then
    MODE=$(jq -r '.mode // "toggle"' "$CFG")
    KEY=$(jq -r '.keyboard_key // "Pause"' "$CFG")
    DAEMON=$(jq -r 'if .keyboard_daemon == false then "false" else "true" end' "$CFG")
  else
    raw_mode=$(grep -oE '"mode"[[:space:]]*:[[:space:]]*"[^"]+"' "$CFG" | head -1 | sed -E 's/.*"([^"]+)"[[:space:]]*$/\1/') || true
    raw_key=$(grep -oE '"keyboard_key"[[:space:]]*:[[:space:]]*"[^"]+"' "$CFG" | head -1 | sed -E 's/.*"([^"]+)"[[:space:]]*$/\1/') || true
    [[ -n "${raw_mode:-}" ]] && MODE=$raw_mode
    [[ -n "${raw_key:-}" ]] && KEY=$raw_key
    if grep -q '"keyboard_daemon"[[:space:]]*:[[:space:]]*false' "$CFG" 2>/dev/null; then
      DAEMON=false
    fi
  fi
fi

case "${KEY}" in
  ScrollLock | scrolllock | Scroll_lock | SCROLLLOCK) KEY=Scroll_Lock ;;
  CapsLock | capslock | Caps_lock) KEY=Caps_Lock ;;
  Pause | pause | Break | break) KEY=Pause ;;
esac

mkdir -p "$(dirname "$OUT")"

if [[ "$DAEMON" == "true" ]]; then
  cat >"$OUT" <<EOF
// Generated by dictation-ptt sync-niri-bind.sh — do not edit by hand.
// keyboard_daemon=true → Scroll_Lock handled by dictation-ptt-keys (evdev PTT).
// Empty binds block keeps the optional include valid.
binds {
}
EOF
else
  # Fallback without daemon: toggle only (no key-up in niri).
  cat >"$OUT" <<EOF
// Generated by dictation-ptt sync-niri-bind.sh — do not edit by hand.
// keyboard_daemon=false → niri toggle fallback (no Key+Release support).
binds {
    ${KEY} allow-when-locked=true repeat=false hotkey-overlay-title="Dictation toggle (niri fallback)" { spawn "${BIN}" "toggle"; }
}
EOF
fi

reload_ok=0
if command -v niri >/dev/null 2>&1; then
  if niri msg action load-config-file >/dev/null 2>&1; then
    reload_ok=1
  fi
fi

if [[ "$reload_ok" -eq 1 ]]; then
  echo "Wrote $OUT (daemon=$DAEMON mode=$MODE key=$KEY) and reloaded niri config."
else
  echo "Wrote $OUT (daemon=$DAEMON mode=$MODE key=$KEY). Reload with: niri msg action load-config-file"
fi
