#!/usr/bin/env bash
# Regenerate ~/.config/niri/dms/dictation-ptt.kdl from dictation-ptt config.json.
#
# niri 26.04 (and wiki as of 2026-08): Key+Release / press+release binds are NOT
# supported yet (niri-wm/niri#3621 still open). Hold mode therefore binds
# press→start only; silence_ms / max_sec (or stop/toggle/DMS) end the session.
# Output is NOT dms/binds.kdl (DMS-owned); config.kdl includes dictation-ptt.kdl optionally.
set -euo pipefail

CFG="${DICTATION_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/dictation-ptt/config.json}"
# Dedicated file: do NOT overwrite dms/binds.kdl (owned/regenerated by DMS).
OUT="${NIRI_DMS_BINDS:-${XDG_CONFIG_HOME:-$HOME/.config}/niri/dms/dictation-ptt.kdl}"
BIN="${DICTATION_BIN:-/run/current-system/sw/bin/dictation-ptt}"

MODE=hold
KEY=Scroll_Lock

if [[ -f "$CFG" ]]; then
  if command -v jq >/dev/null 2>&1; then
    MODE=$(jq -r '.mode // "hold"' "$CFG")
    KEY=$(jq -r '.keyboard_key // "Scroll_Lock"' "$CFG")
  else
    # Minimal fallback without jq (keep defaults on parse failure).
    raw_mode=$(grep -oE '"mode"[[:space:]]*:[[:space:]]*"[^"]+"' "$CFG" | head -1 | sed -E 's/.*"([^"]+)"[[:space:]]*$/\1/') || true
    raw_key=$(grep -oE '"keyboard_key"[[:space:]]*:[[:space:]]*"[^"]+"' "$CFG" | head -1 | sed -E 's/.*"([^"]+)"[[:space:]]*$/\1/') || true
    [[ -n "${raw_mode:-}" ]] && MODE=$raw_mode
    [[ -n "${raw_key:-}" ]] && KEY=$raw_key
  fi
fi

# Accept friendly aliases; niri requires XKB keysym names (Scroll_Lock, not ScrollLock).
case "${KEY}" in
  ScrollLock | scrolllock | Scroll_lock | SCROLLLOCK) KEY=Scroll_Lock ;;
  CapsLock | capslock | Caps_lock) KEY=Caps_Lock ;;
esac

mkdir -p "$(dirname "$OUT")"

if [[ "$MODE" == "toggle" ]]; then
  cat >"$OUT" <<EOF
// Generated by dictation-ptt sync-niri-bind.sh — do not edit by hand.
// mode=toggle key=${KEY}
binds {
    ${KEY} allow-when-locked=true repeat=false hotkey-overlay-title="Dictation toggle" { spawn "${BIN}" "toggle"; }
}
EOF
else
  cat >"$OUT" <<EOF
// Generated by dictation-ptt sync-niri-bind.sh — do not edit by hand.
// mode=hold key=${KEY}
// niri has no key-release binds yet: press starts listening; silence/max-duration (or stop) ends it.
binds {
    ${KEY} allow-when-locked=true repeat=false hotkey-overlay-title="Dictation hold (press=start)" { spawn "${BIN}" "start"; }
}
EOF
fi

reload_ok=0
if command -v niri >/dev/null 2>&1; then
  if niri msg action load-config-file >/dev/null 2>&1; then
    reload_ok=1
  fi
fi

if [[ "$reload_ok" -eq 1 ]]; then
  echo "Wrote $OUT (mode=$MODE key=$KEY) and reloaded niri config."
else
  echo "Wrote $OUT (mode=$MODE key=$KEY). Reload with: niri msg action load-config-file"
fi
